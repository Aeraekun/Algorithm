SELECT I.NAME NAME, I.DATETIME DATETIME
  FROM ANIMAL_INS I
 WHERE NOT EXISTS (
     SELECT 1
       FROM ANIMAL_OUTS O
      WHERE O.ANIMAL_ID = I.ANIMAL_ID
 )
 ORDER BY DATETIME
 FETCH FIRST 3 ROWS ONLY